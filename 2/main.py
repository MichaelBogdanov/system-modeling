import random

# -----------------------------
# 1. Параметры задания
# -----------------------------
N = 90   # всего нужно сгенерировать значений
q = 15   # сколько первых значений вывести

# Для повторяемого результата задаём фиксированное "зерно" случайности.
# Если его убрать, каждый запуск будет давать немного другие числа.
# random.seed(42)

# -----------------------------
# 2. Генерация случайной величины
# -----------------------------
# По методу обратной функции:
# F(x) = x^4
# значит x = r^(1/4), где r — обычное число от 0 до 1.
sample = [random.random() ** 0.25 for _ in range(N)]

# -----------------------------
# 3. Вывод первых q значений
# -----------------------------
print(f"Первые {q} значений случайной величины:")
for i, value in enumerate(sample[:q], start=1):
    print(f"{i:2d}: {value:.6f}")

# -----------------------------
# 4. Точные значения
# -----------------------------
# Для f(x) = 4x^3 на (0, 1):
# M = 4/5
# D = 2/75
M_exact = 4 / 5
D_exact = 2 / 75

print("\nТочные значения:")
print(f"M = {M_exact:.6f}")
print(f"D = {D_exact:.6f}")

# -----------------------------
# 5. Оценка математического ожидания по выборке
# -----------------------------
m = sum(sample) / N

# -----------------------------
# 6. Оценка дисперсии по выборке
# -----------------------------
# Сначала считаем среднее по всей выборке.
# Потом считаем разброс относительно этого среднего.
# Делим на N-1 — это и есть несмещённая оценка.
g = sum((x - m) ** 2 for x in sample) / (N - 1)

print("\nОценки по выборке:")
print(f"m = {m:.6f}")
print(f"g = {g:.6f}")

# -----------------------------
# 7. Сравнение с точными значениями
# -----------------------------
print("\nСравнение:")
print(f"|m - M| = {abs(m - M_exact):.6f}")
print(f"|g - D| = {abs(g - D_exact):.6f}")